// Builds src/data/aiStarterCurriculum.ts from the Starter lesson snapshot:
// lesson titles from the manifest, YouTube IDs from each lesson file, and
// video durations read from YouTube's public watch page.
// Usage: node scripts/build-starter-curriculum.mjs
import fs from "node:fs";

const BASE = "public/learn-content/ai-starter";
const OUT = "src/data/aiStarterCurriculum.ts";
const manifest = JSON.parse(fs.readFileSync(`${BASE}/manifest.json`, "utf8"));

async function youtubeSeconds(id) {
  const res = await fetch(`https://www.youtube.com/watch?v=${id}`, {
    headers: { "User-Agent": "Mozilla/5.0", "Accept-Language": "en" },
  });
  const match = (await res.text()).match(/"lengthSeconds":"(\d+)"/);
  if (!match) throw new Error(`No duration for ${id}`);
  return Number(match[1]);
}

const topics = [];
for (const topic of manifest.topics) {
  const lessons = [];
  for (const lesson of topic.lessons) {
    const md = fs.readFileSync(`${BASE}/${topic.slug}/${lesson.slug}.md`, "utf8");
    const id = md.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|watch\?v=))([A-Za-z0-9_-]{11})/)?.[1];
    if (!id) throw new Error(`No video in ${topic.slug}/${lesson.slug}`);
    lessons.push({ slug: lesson.slug, title: lesson.title, videoId: id, seconds: await youtubeSeconds(id) });
  }
  topics.push({ slug: topic.slug, title: topic.title, lessons });
}

fs.writeFileSync(OUT, `// Generated by scripts/build-starter-curriculum.mjs — do not edit by hand.
export const aiStarterCurriculum = ${JSON.stringify({ topics }, null, 2)};
`);
const total = topics.flatMap(t => t.lessons).reduce((sum, l) => sum + l.seconds, 0);
console.log(`Wrote ${OUT}: ${topics.length} topics, ${topics.flatMap(t => t.lessons).length} lessons, ${Math.floor(total / 3600)}h ${Math.floor((total % 3600) / 60)}m`);
